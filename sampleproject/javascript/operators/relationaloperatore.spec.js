/*
Relational / Conditional Operator
Output of these operator always must be boolean value
 
    >   -   greater than
    <   -   Lesser than
    >=  -   Greater than equal to
    <=  -   Less than equal to
    ==  - Equal to
    === - Exact Eqaul to
    !=  -   Not Equal to
*/
